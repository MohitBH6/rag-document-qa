"""
Streaming Module

This module handles token-level streaming for real-time response display.
"""

import logging
import sys
from typing import Any, Optional, Iterator
from langchain_core.callbacks import BaseCallbackHandler

logger = logging.getLogger(__name__)


class StreamingCallbackHandler(BaseCallbackHandler):
    """
    Custom callback handler for streaming LLM output.

    This handler captures tokens as they're generated by the LLM
    and prints them immediately for a better user experience.

    Why streaming matters:
    - LLMs can take 10+ seconds to generate complete responses
    - Without streaming, users see nothing until completion
    - With streaming, users see progress immediately
    - Reduces perceived latency and improves UX
    """

    def __init__(self, color: Optional[str] = None):
        """
        Initialize streaming handler.

        Args:
            color: ANSI color code for output (optional)
        """
        self.color = color
        self.text = ""  # Accumulate full response

    def on_llm_new_token(self, token: str, **kwargs: Any) -> None:
        """
        Called when LLM generates a new token.

        This is the core streaming method - it's called for each
        token as the model generates the response.

        Args:
            token: New token from the LLM
            **kwargs: Additional callback arguments
        """
        # Print token immediately with flush=True for instant display
        # The end="" prevents newlines between tokens
        sys.stdout.write(token)
        sys.stdout.flush()

        # Also accumulate for later use
        self.text += token

    def on_llm_end(self, response: Any, **kwargs: Any) -> None:
        """
        Called when LLM completes generation.

        Args:
            response: Final LLM response
            **kwargs: Additional callback arguments
        """
        # Print newline after completion
        print()
        logger.debug(f"Streaming completed. Total tokens: {len(self.text.split())}")


def stream_chain_response(chain, query: str) -> str:
    """
    Stream response from a chain and return complete text.

    This function demonstrates how to use LCEL's built-in streaming
    support. All LCEL chains automatically support .stream() method.

    Args:
        chain: LangChain chain with streaming support
        query: User query

    Returns:
        Complete response text
    """
    try:
        logger.info("Streaming response...")

        full_response = ""

        # Use the chain's .stream() method
        # This returns an iterator that yields chunks as they're generated
        for chunk in chain.stream(query):
            # Print each chunk immediately
            print(chunk, end="", flush=True)
            full_response += chunk

        # Print newline after streaming completes
        print()

        return full_response

    except Exception as e:
        logger.error(f"❌ Error during streaming: {e}")
        raise


def format_streaming_response(
        response: str,
        sources: list,
        show_sources: bool = True
) -> None:
    """
    Format and display streaming response with sources.

    This provides a clean output format that separates the answer
    from the source citations.

    Args:
        response: Generated response text
        sources: List of source documents
        show_sources: Whether to display source citations
    """
    print("\n" + "=" * 60)
    print("ANSWER:")
    print("=" * 60)
    print(response)

    if show_sources and sources:
        print("\n" + "=" * 60)
        print("SOURCES:")
        print("=" * 60)

        # Format sources with page numbers
        for i, doc in enumerate(sources, 1):
            source = doc.metadata.get('source', 'Unknown')
            page = doc.metadata.get('page', 'N/A')

            # Clean up source path (show just filename)
            source_name = source.split('/')[-1] if '/' in source else source

            print(f"{i}. {source_name} (page {page})")

            # Optionally show snippet
            snippet = doc.page_content[:150] + "..." if len(doc.page_content) > 150 else doc.page_content
            print(f"   Preview: {snippet}")
            print()


class TokenCounter:
    """
    Utility class to count tokens during streaming.

    Useful for monitoring token usage and costs.
    """

    def __init__(self):
        """Initialize token counter."""
        self.token_count = 0
        self.start_time = None
        self.end_time = None

    def start(self) -> None:
        """Start timing."""
        import time
        self.start_time = time.time()
        self.token_count = 0

    def add_token(self, _token: str) -> None:
        """
        Count a token.

        Args:
            _token: Token string
        """
        self.token_count += 1

    def stop(self) -> dict:
        """
        Stop timing and return statistics.

        Returns:
            Dictionary with timing and token statistics
        """
        import time
        self.end_time = time.time()

        duration = self.end_time - self.start_time if self.start_time else 0
        tokens_per_second = self.token_count / duration if duration > 0 else 0

        return {
            "total_tokens": self.token_count,
            "duration_seconds": duration,
            "tokens_per_second": tokens_per_second
        }


def create_streaming_chain(chain, query: str) -> Iterator[str]:
    """
    Create a streaming iterator from a chain.

    This is a generator function that yields chunks as they arrive,
    allowing for flexible consumption of streaming responses.

    Args:
        chain: LangChain chain
        query: User query

    Yields:
        Response chunks as they're generated
    """
    try:
        for chunk in chain.stream(query):
            yield chunk
    except Exception as e:
        logger.error(f"❌ Streaming error: {e}")
        yield f"\n[Error: {str(e)}]"


def compare_streaming_vs_non_streaming(chain, query: str) -> dict:
    """
    Compare performance of streaming vs non-streaming modes.

    Educational function to demonstrate streaming benefits.

    Args:
        chain: LangChain chain
        query: User query

    Returns:
        Dictionary with timing comparison
    """
    import time

    results = {}

    # Test non-streaming
    print("\n🔹 Testing non-streaming mode...")
    start = time.time()
    non_streaming_response = chain.invoke(query)
    non_streaming_time = time.time() - start

    print(f"Non-streaming response received in {non_streaming_time:.2f}s")
    results['non_streaming'] = {
        'duration': non_streaming_time,
        'response': non_streaming_response
    }

    # Test streaming
    print("\n🔹 Testing streaming mode...")
    start = time.time()
    first_token_time = None
    streaming_response = ""

    for i, chunk in enumerate(chain.stream(query)):
        if i == 0:
            first_token_time = time.time() - start
        streaming_response += chunk

    total_streaming_time = time.time() - start

    print(f"\nStreaming completed in {total_streaming_time:.2f}s")
    print(f"Time to first token: {first_token_time:.2f}s")

    results['streaming'] = {
        'duration': total_streaming_time,
        'first_token_time': first_token_time,
        'response': streaming_response
    }

    # Print comparison
    print("\n" + "=" * 60)
    print("COMPARISON:")
    print("=" * 60)
    print(f"Non-streaming total time: {non_streaming_time:.2f}s")
    print(f"Streaming total time: {total_streaming_time:.2f}s")
    print(f"Streaming first token: {first_token_time:.2f}s")
    print(f"User waited (streaming): {first_token_time:.2f}s")
    print(f"User waited (non-streaming): {non_streaming_time:.2f}s")
    print(f"Improvement: {(non_streaming_time - first_token_time):.2f}s faster to first output")
    print("=" * 60)

    return results